#!/usr/bin/env python3
"""Build docs/TIMELINE.md from the frontmatter of cases/ and entities/, and report broken [[wikilinks]].

usage:
  python3 -I tools/build_index.py            # writes docs/TIMELINE.md, prints the link report
  python3 -I tools/build_index.py --check    # link report only, nothing written; exit 1 if broken links

No dependencies. The frontmatter parser handles only what the templates use:
scalars, one-line lists [a, b] and one-line dicts {k: v, ...}. Run from anywhere.
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FOLDERS = ["cases", "entities", "docs", "sources", "assets", "ko", "ko/cases"]
FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
LINK_RE = re.compile(r"\[\[([^\]]+?)\]\]")
TODAY = datetime.date.today().isoformat()


def parse_fm(text):
    m = FM_RE.match(text)
    if not m:
        return {}
    d = {}
    for line in m.group(1).splitlines():
        line = re.sub(r"\s+#.*$", "", line).rstrip()
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        k, v = line.split(":", 1)
        k, v = k.strip(), v.strip()
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            v = [x.strip().strip("\"'") for x in inner.split(",")] if inner else []
        elif v.startswith("{") and v.endswith("}"):
            dd = {}
            for part in v[1:-1].split(","):
                if ":" in part:
                    kk, vv = part.split(":", 1)
                    dd[kk.strip()] = vv.strip().strip("\"'")
            v = dd
        else:
            v = v.strip("\"'")
        d[k] = v
    return d


def md_files():
    seen = set()
    for folder in FOLDERS:
        p = ROOT / folder
        if not p.is_dir():
            continue
        for f in sorted(p.glob("*.md")):
            if f.name.startswith("_TEMPLATE"):
                continue
            if f.resolve() not in seen:
                seen.add(f.resolve())
                yield f
    readme = ROOT / "README.md"
    if readme.exists():
        yield readme


def main():
    check_only = "--check" in sys.argv
    files = list(md_files())
    stems = {f.stem for f in files} | {"index", "TIMELINE"}
    cases, entities, broken, nlinks = [], [], [], 0

    for f in files:
        text = f.read_text(encoding="utf-8")
        fm = parse_fm(text)
        rel = f.relative_to(ROOT).as_posix()
        if rel.startswith("cases/") and f.name != "index.md":
            cases.append((fm, rel))
        elif rel.startswith("entities/") and f.name != "index.md":
            entities.append((fm, rel))
        # `[[id]]` inside code spans and fenced blocks is documentation, not a link.
        scan = re.sub(r"```.*?```", "", text, flags=re.S)
        scan = re.sub(r"`[^`\n]*`", "", scan)
        for raw in LINK_RE.findall(scan):
            nlinks += 1
            target = raw.replace("\\|", "|").split("|")[0].split("#")[0].strip()
            if target and target not in stems:
                broken.append((rel, target))

    def yr(fm, key):
        v = fm.get(key, "")
        try:
            return int(str(v)[:4])
        except ValueError:
            return 9999

    cases.sort(key=lambda c: (yr(c[0], "event_year"), c[1]))
    entities.sort(key=lambda e: (str(e[0].get("dates", ""))[:4] or "9999", e[1]))

    out = [
        "---",
        "title: Timeline",
        f"updated: {TODAY}",
        "---",
        "",
        "# Timeline (generated)",
        "",
        "Generated by `tools/build_index.py` from the frontmatter of `cases/` and `entities/`. Do not edit by hand; "
        "edit the cards and entities and run the script again. Grades are explained in [[METHOD]].",
        "",
        "## Cases by event year",
        "",
        "Columns: event year → year of the first record · card · phenomenon code and variant · cluster and country · "
        "investigator or collecting body · grades as R · V · I · counted layers (S, V, SV or no) · status.",
        "",
        "| Years | Card | Type | Cluster | Investigator | Grades | Status |",
        "|---|---|---|---|---|---|---|",
    ]
    for fm, rel in cases:
        cid = fm.get("id", pathlib.Path(rel).stem)
        inv = fm.get("investigator", "")
        inv = f"[[{inv}]]" if inv and inv in stems else inv
        out.append(
            f"| {fm.get('event_year', '')} → {fm.get('record_year', '')} | [[{cid}\\|{fm.get('title', cid)}]] | "
            f"{fm.get('code', '')} · {fm.get('variant', '')} | {fm.get('cluster', '')} · {fm.get('country', '')} | "
            f"{inv} | {fm.get('grade_R', '')} · {fm.get('grade_V', '')} · {fm.get('independence', '')} · "
            f"{fm.get('countable', '')} | {fm.get('status', '')} |"
        )
    out += ["", "## Entities", "", "| Dates | Entity | Type · role | Linked to |", "|---|---|---|---|"]
    for fm, rel in entities:
        eid = fm.get("id", pathlib.Path(rel).stem)
        links = fm.get("links", [])
        links = ", ".join(f"[[{x}]]" for x in links) if isinstance(links, list) else str(links)
        out.append(f"| {fm.get('dates', '')} | [[{eid}\\|{fm.get('name', eid)}]] | {fm.get('type', '')} · {fm.get('role', '')} | {links} |")
    out += ["", "## Link check", "", f"- {nlinks} wikilinks in {len(files)} files checked on {TODAY}."]
    if broken:
        out.append(f"- {len(broken)} link(s) point to pages that do not exist yet (planned cards count as leads, not records):")
        for rel, target in broken:
            out.append(f"  - `{rel}` → `{target}`")
    else:
        out.append("- No broken links.")
    out.append("")

    report = "\n".join(out[out.index("## Link check"):])
    print(report)
    if check_only:
        sys.exit(1 if broken else 0)
    (ROOT / "docs" / "TIMELINE.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/TIMELINE.md ({len(cases)} cases, {len(entities)} entities)")


if __name__ == "__main__":
    main()
